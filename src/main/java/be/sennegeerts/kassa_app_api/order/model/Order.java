package be.sennegeerts.kassa_app_api.order.model;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;

import be.sennegeerts.kassa_app_api.event.model.Event;
import jakarta.persistence.*;

/** One confirmed sale (what the "Clear" button does today). Table is "orders": ORDER is reserved in SQL. */
@Entity
@Table(name = "orders")
public class Order {
 
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;
 
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "event_id", nullable = false)
    private Event event;
 
    /** Generated by the frontend per sale; unique, so a retried request can't book the sale twice. */
    @Column(name = "client_id", nullable = false, updatable = false, unique = true)
    private UUID clientId;
 
    @Column(nullable = false, precision = 10, scale = 2)
    private BigDecimal total = BigDecimal.ZERO;
 
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt = Instant.now();
 
    @OneToMany(mappedBy = "order", cascade = CascadeType.ALL, orphanRemoval = true)
    private List<OrderLine> lines = new ArrayList<>();
 
    protected Order() {}
 
    public Order(Event event, UUID clientId) {
        this.event = event;
        this.clientId = clientId;
    }
 
    /** Always add lines through here so the total can never drift from the lines. */
    public void addLine(OrderLine line) {
        lines.add(line);
        line.setOrder(this);
        total = total.add(line.getUnitPrice().multiply(BigDecimal.valueOf(line.getQuantity())));
    }
 
    public UUID getId() { return id; }
    public Event getEvent() { return event; }
    public UUID getClientId() { return clientId; }
    public BigDecimal getTotal() { return total; }
    public Instant getCreatedAt() { return createdAt; }
    public List<OrderLine> getLines() { return List.copyOf(lines); }
}
